from pathlib import Path
from typing import Dict, List

from .. import __tool_name__, __version__
from ..models import SEVERITIES, Finding, Location, SourceFile
from ..rules.secrets import find_secrets, mask_value

SCOPE_LIMITATIONS = [
    "Static source-code review only; no code, exploit or dynamic test was executed.",
    "No runtime penetration testing, dependency (SCA) audit or infrastructure review was performed.",
    "Findings marked \"Needs validation\" depend on deployment/runtime context that is not visible in the code.",
    "AI-assisted analysis can miss issues or misjudge context; every finding is grounded to a verified code line, "
    "but should still be confirmed by a developer before remediation is closed.",
    "Credential-like values were masked in this report and before any code was sent to an AI provider.",
]


def masked_lines(f: SourceFile) -> List[str]:
    lines = f.lines
    for h in find_secrets(f):
        i = h.line - 1
        if 0 <= i < len(lines):
            lines[i] = lines[i].replace(h.value, mask_value(h.value))
    return lines


class Context:
    def __init__(self, result):
        self.result = result
        self.files: Dict[str, SourceFile] = {f.path: f for f in result.files}
        self._masked: Dict[str, List[str]] = {}

    def lines(self, path: str) -> List[str]:
        if path not in self._masked:
            f = self.files.get(path)
            self._masked[path] = masked_lines(f) if f else []
        return self._masked[path]

    def excerpt(self, loc: Location, pad: int = 2):
        """[(line_no, text, is_target)]"""
        lines = self.lines(loc.file)
        if not lines:
            return [(loc.start_line, loc.snippet, True)]
        s = max(1, loc.start_line - pad)
        e = min(len(lines), max(loc.end_line, loc.start_line) + pad)
        return [(i, lines[i - 1], loc.start_line <= i <= max(loc.end_line, loc.start_line)) for i in range(s, e + 1)]


def fence(text: str, lang: str = "") -> str:
    longest = max((len(m) for m in re.findall(r"`+", text or "")), default=0)
    ticks = "`" * max(3, longest + 1)
    return f"{ticks}{lang}\n{text}\n{ticks}"


def lang_for(path: str) -> str:
    ext = path.rsplit(".", 1)[-1].lower() if "." in path else ""
    return {"ts": "typescript", "tsx": "tsx", "js": "javascript", "jsx": "jsx", "py": "python", "sql": "sql",
            "html": "html", "yml": "yaml", "yaml": "yaml", "toml": "toml", "env": "bash", "sh": "bash"}.get(ext, "")


def counts(result) -> Dict[str, int]:
    c = {s: 0 for s in SEVERITIES}
    for f in result.findings:
        c[f.severity] += 1
    return c


def source_label(f: Finding) -> str:
    return {"rule+ai": "Rule engine + AI verification", "ai": "AI discovery (evidence-grounded)",
            "rule": "Rule engine (not AI-verified)"}.get(f.source, f.source)


# ------------------------------------------------------------------ markdown

def to_markdown(result) -> str:
    ctx = Context(result)
    c = counts(result)
    s = result.summary
    m = result.metrics
    out: List[str] = []
    w = out.append
    w(f"# Security Assessment Report: {result.project}\n")
    w(f"> Generated by **{__tool_name__} v{__version__}** - AI-assisted static code security review.\n")
    w("## 1. Assessment Information\n")
    w("| Item | Value |\n|---|---|")
    w(f"| Application / repository | `{result.project}` |")
    w("| Assessment type | AI-assisted static code review (rule engine + LLM verification) |")
    w(f"| Assessment date | {result.started} |")
    w(f"| Tool | {__tool_name__} v{__version__} |")
    w(f"| AI model | {result.ai_label} |")
    w(f"| Detected stack | {', '.join(result.frameworks) or 'n/a'} |")
    w(f"| Scope | {m.files_collected} files, {m.lines_scanned} lines |")
    w(f"| Overall risk rating | **{s.get('risk_rating')}** |\n")
    w("## 2. Executive Summary\n")
    w(s.get("executive_summary", "") + "\n")
    if not result.ai_enabled:
        w("> **Note:** this report was produced in rules-only mode. AI verification, contextual explanations and "
          "AI-discovered findings are not included. Re-run with an AI provider for the full assessment.\n")
    w("## 3. Findings Summary\n")
    w("| Severity | Count |\n|---|---:|")
    for sev in SEVERITIES:
        if sev == "Info" and not c[sev]:
            continue
        w(f"| {sev} | {c[sev]} |")
    w(f"| **Total** | **{len(result.findings)}** |\n")
    if result.findings:
        w("| ID | Severity | Title | Location | Status |\n|---|---|---|---|---|")
        for f in result.findings:
            more = f" (+{len(f.locations) - 1})" if len(f.locations) > 1 else ""
            w(f"| [{f.id}](#{f.id.lower()}) | {f.severity} | {_md_cell(f.title)} | `{f.primary.label()}`{more} | {f.status} |")
        w("")
    w("## 4. Detailed Findings\n")
    if not result.findings:
        w("No findings at or above the selected severity threshold.\n")
    current = None
    for f in result.findings:
        if f.severity != current:
            current = f.severity
            w(f"### {current} severity\n")
        w(f"<a id=\"{f.id.lower()}\"></a>\n")
        w(f"#### {f.id}: {f.title}\n")
        w(f"| | |\n|---|---|")
        w(f"| **Severity** | {f.severity}{' (AI recalibrated: ' + f.ai_severity_change + ')' if f.ai_severity_change else ''} |")
        w(f"| **Status / confidence** | {f.status} / {f.confidence} confidence |")
        w(f"| **Category** | {f.category} |")
        w(f"| **CWE** | {f.cwe} |")
        if f.owasp:
            w(f"| **OWASP Top 10** | {f.owasp} |")
        locs = "<br>".join(f"`{l.label()}`" for l in f.locations)
        w(f"| **Affected location(s)** | {locs} |")
        w(f"| **Detection** | {source_label(f)}{' - rule ' + f.rule_id if f.rule_id else ''} |\n")
        w("**Description**\n")
        w(f.description + "\n")
        w("**Vulnerable code (evidence)**\n")
        for l in f.locations[:4]:
            ex = ctx.excerpt(l)
            body = "\n".join(f"{'>' if t else ' '} {n:>4} | {txt}" for n, txt, t in ex)
            w(f"`{l.label()}`\n")
            w(fence(body, "") + "\n")
        if len(f.locations) > 4:
            w(f"*...and {len(f.locations) - 4} more location(s).* \n")
        w("**Potential impact**\n")
        w((f.impact or "-") + "\n")
        w("**Recommended fix**\n")
        w((f.recommendation or "-") + "\n")
        if f.secure_code:
            w("**Secure code example**\n")
            w(fence(f.secure_code, f.secure_code_lang or lang_for(f.primary.file)) + "\n")
        if f.validation_notes:
            w("**Validation notes / assumptions**\n")
            w(f.validation_notes + "\n")
        if f.references:
            w("**References:** " + ", ".join(f"<{r}>" for r in f.references[:3]) + "\n")
        w("---\n")
    if s.get("attack_chains"):
        w("## 5. Attack Chains\n")
        w("How individual weaknesses combine into higher-impact attack paths:\n")
        for ch in s["attack_chains"]:
            w(f"- **{ch['title']}** ({', '.join(ch['finding_ids'])}): {ch['narrative']}")
        w("")
    w("## 6. Remediation Plan\n")
    w("| Priority | Action | Findings | Effort |\n|---:|---|---|---|")
    for i, a in enumerate(s.get("prioritized_actions", []), start=1):
        w(f"| {i} | {_md_cell(a['action'])} | {', '.join(a['finding_ids'])} | {a.get('effort', '')} |")
    w("")
    w("### Remediation summary by finding\n")
    w("| Finding | Severity | Recommended action |\n|---|---|---|")
    for f in result.findings:
        first = re.split(r"(?<=[.!?])\s", (f.recommendation or f.title).strip())[0]
        w(f"| {f.id} | {f.severity} | {_md_cell(first)} |")
    w("")
    w("## 7. Overall Assessment\n")
    w(f"**Risk rating: {s.get('risk_rating')}** (weighted risk score {s.get('risk_score')}).\n")
    w((s.get("overall_assessment") or "") + "\n")
    if s.get("positive_observations"):
        w("**Positive observations**\n")
        for p in s["positive_observations"]:
            w(f"- {p}")
        w("")
    w("## 8. Methodology and AI Pipeline Metrics\n")
    w("1. **Collect** - source files are loaded from a folder, ZIP or GitHub URL (treated as untrusted data; nothing is executed).")
    w("2. **Detect candidates** - generic, language-aware rules (secrets, injection, XSS, access control, RLS policy analysis, configuration).")
    w("3. **Protect** - credential-like values are masked before any code leaves the machine.")
    w("4. **AI review** - each file is reviewed by an LLM with project context (stack, file map, database schema and policies): it confirms or rejects every rule candidate, re-scores severity and finds logic flaws the rules cannot see.")
    w("5. **Ground** - every AI finding must quote an exact code line; unverifiable findings are dropped.")
    w("6. **Deduplicate** - findings sharing a root cause are merged into one finding with multiple locations.")
    w("7. **Synthesise** - the AI writes the executive summary, attack chains and remediation plan from verified findings only.\n")
    w("| Metric | Value |\n|---|---:|")
    rows = [
        ("Files analysed", m.files_collected), ("Files reviewed by AI", m.files_ai_reviewed),
        ("Rule candidates", m.rule_candidates), ("Candidates rejected by AI as false positives", m.ai_rejected),
        ("Severity recalibrations by AI", m.ai_severity_adjusted), ("New findings discovered by AI", m.ai_new_findings),
        ("AI findings dropped by evidence grounding", m.grounding_dropped), ("Duplicates merged", m.merged_duplicates),
        ("Secret values masked before AI", m.secrets_redacted), ("AI requests (cache hits)", f"{m.ai_calls} ({m.ai_cache_hits})"),
        ("Scan duration", f"{result.duration_s}s"),
    ]
    for k, v in rows:
        w(f"| {k} | {v} |")
    if m.injection_markers:
        w(f"\n> {m.injection_markers} file(s) contained text resembling instructions to an AI model; it was treated as data.")
    if m.ai_errors:
        w(f"\n> {m.ai_errors} AI request(s) failed; affected files fall back to rule findings. "
          + "; ".join(m.ai_error_messages[:2]))
    w("")
    w("## 9. Scope and Limitations\n")
    for lim in SCOPE_LIMITATIONS:
        w(f"- {lim}")
    w("")
    w("## 10. Conclusion\n")
    crit = [f.id for f in result.findings if f.severity in ("Critical", "High")]
    if crit:
        w(f"Remediate {', '.join(crit[:8])}{' and the other High findings' if len(crit) > 8 else ''} before any "
          "production exposure, then address Medium and Low items as hardening. Re-run the review after fixes "
          "are applied and add regression tests for each corrected weakness.\n")
    else:
        w("No Critical or High issues were identified. Address remaining items as hardening and re-run the review "
          "after significant changes.\n")
    return "\n".join(out)


def _md_cell(t: str) -> str:
    return (t or "").replace("|", "\\|").replace("\n", " ")


# ------------------------------------------------------------------ JSON

def to_json(result) -> str:
    data = {
        "tool": {"name": __tool_name__, "version": __version__},
        "project": result.project, "started": result.started, "duration_s": result.duration_s,
        "ai_model": result.ai_label, "ai_enabled": result.ai_enabled, "frameworks": result.frameworks,
        "counts": counts(result), "summary": result.summary, "metrics": result.metrics.to_dict(),
        "findings": [_finding_json(f) for f in result.findings],
    }
    return json.dumps(data, indent=2)


def _finding_json(f: Finding) -> Dict:
    d = f.to_dict()
    return d


# ------------------------------------------------------------------ SARIF

SARIF_LEVEL = {"Critical": "error", "High": "error", "Medium": "warning", "Low": "note", "Info": "note"}
SARIF_SCORE = {"Critical": "9.5", "High": "8.0", "Medium": "5.5", "Low": "3.0", "Info": "0.0"}


def to_sarif(result) -> str:
    rules, rule_index = [], {}
    results = []
    for f in result.findings:
        rid = f.rule_id or f"CW-AI-{f.cwe}"
        if rid not in rule_index:
            rule_index[rid] = len(rules)
            rules.append({
                "id": rid, "name": re.sub(r"[^A-Za-z0-9]", "", f.category.title()) or "SecurityIssue",
                "shortDescription": {"text": f.title[:200]},
                "fullDescription": {"text": f.description[:1000]},
                "help": {"text": f.recommendation[:2000]},
                "properties": {"tags": ["security", f.cwe], "security-severity": SARIF_SCORE[f.severity]},
            })
        results.append({
            "ruleId": rid, "ruleIndex": rule_index[rid], "level": SARIF_LEVEL[f.severity],
            "message": {"text": f"[{f.id}] {f.title}: {f.description[:500]}"},
            "locations": [{"physicalLocation": {
                "artifactLocation": {"uri": l.file},
                "region": {"startLine": l.start_line, "endLine": max(l.end_line, l.start_line)}}}
                for l in f.locations],
            "properties": {"severity": f.severity, "status": f.status, "confidence": f.confidence,
                           "cwe": f.cwe, "source": f.source},
        })
    sarif = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json", "version": "2.1.0",
        "runs": [{"tool": {"driver": {"name": __tool_name__, "version": __version__,
                                      "informationUri": "https://github.com/", "rules": rules}},
                  "results": results}],
    }
    return json.dumps(sarif, indent=2)


# ------------------------------------------------------------------ writer

def write_reports(result, out_dir: Path, basename: str, formats: List[str]) -> List[Path]:
    from .html import to_html
    out_dir.mkdir(parents=True, exist_ok=True)
    writers = {"md": to_markdown, "html": to_html, "json": to_json, "sarif": to_sarif}
    paths = []
    for fmt in formats:
        fmt = fmt.strip().lower()
        if fmt not in writers:
            continue
        ext = "sarif" if fmt == "sarif" else fmt
        p = out_dir / f"{basename}.{ext}"
        p.write_text(writers[fmt](result), encoding="utf-8")
        paths.append(p)
    return paths
