"""Base classes and helpers for CodeWarden's static candidate rules.

Rules are deliberately *generic* (framework/language patterns, never app-specific
answers). They produce candidate findings that the AI layer later confirms, rejects,
re-scores and explains.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Callable, Dict, Iterable, List, Optional, Sequence

from ..models import Finding, Location, SourceFile

COMMENT_PREFIXES = ("//", "#", "--", "*", "/*", "<!--")

CLIENT_PATH_HINTS = re.compile(r"(^|/)(src|app|pages|components|public|client|frontend|web)(/|$)", re.I)
SERVER_PATH_HINTS = re.compile(r"(^|/)(api|server|backend|functions|routes|controllers|supabase|lambda|handlers)(/|$)", re.I)

TAINT_SOURCES = re.compile(
    r"(req\.(query|params|body|headers|cookies)|request\.(json|form|args|values|get_json|data|body|query)|"
    r"searchParams\.get|url\.searchParams|ctx\.request|event\.(body|queryStringParameters|pathParameters)|"
    r"\$_(GET|POST|REQUEST|COOKIE)|getParameter\(|input\(|sys\.argv|useSearchParams|location\.(search|hash))"
)


@dataclass
class Match:
    start_line: int
    end_line: int
    snippet: str = ""
    note: str = ""
    severity: Optional[str] = None
    confidence: Optional[str] = None
    status: Optional[str] = None
    title: Optional[str] = None
    extra_locations: List[Location] = field(default_factory=list)
    secure_code: Optional[str] = None  # context-specific fix generated by the rule


@dataclass
class Rule:
    id: str
    title: str
    category: str
    cwe: str
    owasp: str
    severity: str
    confidence: str
    languages: Sequence[str]
    description: str
    impact: str
    recommendation: str
    secure_code: Dict[str, str] = field(default_factory=dict)
    references: List[str] = field(default_factory=list)
    group_across_files: bool = False
    status: str = "Needs validation"
    check: Optional[Callable[[SourceFile, "ProjectContext"], List[Match]]] = None
    # project-level rules return (file_path, Match) pairs from cross-file analysis
    project_check: Optional[Callable[["ProjectContext"], List[tuple]]] = None

    def applies_to(self, f: SourceFile) -> bool:
        return "*" in self.languages or f.language in self.languages

    def to_finding(self, f: SourceFile, m: Match) -> Finding:
        lang = f.language if f.language in self.secure_code else next(iter(self.secure_code), "")
        code = self.secure_code.get(f.language) or self.secure_code.get("*") or (
            next(iter(self.secure_code.values())) if self.secure_code else "")
        notes = m.note
        return Finding(
            title=m.title or self.title,
            category=self.category,
            cwe=self.cwe,
            owasp=self.owasp,
            severity=m.severity or self.severity,
            confidence=m.confidence or self.confidence,
            status=m.status or self.status,
            locations=[Location(f.path, m.start_line, m.end_line, m.snippet)] + list(m.extra_locations),
            description=self.description,
            impact=self.impact,
            recommendation=self.recommendation,
            secure_code=m.secure_code or code,
            secure_code_lang=_fence_lang(f.language if f.language in self.secure_code else lang),
            validation_notes=notes,
            rule_id=self.id,
            source="rule",
            references=list(self.references),
        )


def _fence_lang(lang: str) -> str:
    return {"typescript": "typescript", "javascript": "javascript", "python": "python",
            "sql": "sql", "env": "bash", "*": ""}.get(lang, lang)


# ---------------------------------------------------------------- helpers

def is_comment(line: str) -> bool:
    return line.strip().startswith(COMMENT_PREFIXES)


def line_of_offset(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def snippet(lines: List[str], start: int, end: Optional[int] = None) -> str:
    end = end or start
    start = max(1, start)
    end = min(len(lines), end)
    return "\n".join(lines[start - 1:end])


def regex_lines(f: SourceFile, pattern: re.Pattern, exclude: Optional[re.Pattern] = None,
                skip_comments: bool = True) -> Iterable[Match]:
    lines = f.lines
    for i, line in enumerate(lines, start=1):
        if skip_comments and is_comment(line):
            continue
        if pattern.search(line) and not (exclude and exclude.search(line)):
            yield Match(i, i, line.strip())


def window(lines: List[str], line_no: int, before: int, after: int) -> str:
    lo = max(0, line_no - 1 - before)
    hi = min(len(lines), line_no + after)
    return "\n".join(lines[lo:hi])


def is_client_file(f: SourceFile) -> bool:
    if f.path.endswith((".tsx", ".jsx", ".vue", ".svelte")):
        return not SERVER_PATH_HINTS.search(f.path)
    return bool(CLIENT_PATH_HINTS.search(f.path)) and not SERVER_PATH_HINTS.search(f.path)


def is_test_file(f: SourceFile) -> bool:
    return bool(re.search(r"(^|/)(tests?|__tests__|spec|fixtures?|mocks?)(/|$)|\.(test|spec)\.", f.path, re.I))


def has_taint_source(text: str) -> bool:
    return bool(TAINT_SOURCES.search(text))


class ProjectContext:
    """Cross-file facts used by rules and by the AI prompts."""

    def __init__(self, files: List[SourceFile]):
        self.files = files
        self.by_path = {f.path: f for f in files}
        all_text = "\n".join(f.text for f in files if f.language != "sql")[:2_000_000]
        self.frameworks = detect_frameworks(files, all_text)
        from .sql_model import SqlModel  # local import to avoid cycle
        self.sql = SqlModel([f for f in files if f.language == "sql"])

    def tree(self, limit: int = 250) -> str:
        paths = [f.path for f in self.files]
        out = paths[:limit]
        if len(paths) > limit:
            out.append(f"... ({len(paths) - limit} more files)")
        return "\n".join(out)


def detect_frameworks(files: List[SourceFile], text: str) -> List[str]:
    fw = []
    checks = [
        ("React", r"from ['\"]react['\"]|react-dom"),
        ("Next.js", r"from ['\"]next[/'\"]|next\.config"),
        ("Vue", r"from ['\"]vue['\"]|\.vue\b"),
        ("Express", r"require\(['\"]express['\"]\)|from ['\"]express['\"]"),
        ("Supabase", r"supabase|auth\.uid\(\)"),
        ("Deno edge functions", r"Deno\.serve|Deno\.env"),
        ("Flask", r"from flask import|Flask\(__name__\)"),
        ("Django", r"django\.|from django"),
        ("FastAPI", r"from fastapi import|FastAPI\("),
        ("PostgreSQL", r"CREATE TABLE|postgres|\bpg\b|psycopg"),
        ("Prisma", r"@prisma/client|prisma\."),
    ]
    joined = text + "\n" + "\n".join(f.path for f in files)
    for name, pat in checks:
        if re.search(pat, joined, re.I if name in ("PostgreSQL",) else 0):
            fw.append(name)
    if any(f.language == "sql" for f in files) and "PostgreSQL" not in fw:
        fw.append("SQL")
    return fw
